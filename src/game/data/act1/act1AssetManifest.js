export function getAct1AssetManifestState() {
  const assets = act1AssetManifest.map((asset) => ({
    ...asset,
    runtimeKey: asset.status === 'final_ready' ? asset.finalKey : asset.placeholderKey,
    fallbackKey: asset.placeholderKey,
    loadedFinalKey: asset.status === 'final_ready' ? asset.finalKey : null,
    usingPlaceholder: asset.status !== 'final_ready',
  }));
  return {
    assets,
    requiredCount: assets.filter((asset) => asset.requiredForObservedExpected).length,
    finalReadyCount: assets.filter((asset) => asset.status === 'final_ready').length,
    missingFinal: assets.filter((asset) => asset.requiredForObservedExpected && asset.status !== 'final_ready').map((asset) => asset.id),
    generatedRuntimeArt: false,
  };
}
